Console.WriteLine("Digite uma letra para identificar se é vogal ou consoante");
//entrada de usuário
string letra = Console.ReadLine();

//dá a condição
if (letra == "A" && "E" || "I" || "O" || "U") 
{
	Console.WriteLine("A letra digitada é uma vogal");
} else 
{
	Console.WriteLine("A letra digitada é uma consoante");
}

